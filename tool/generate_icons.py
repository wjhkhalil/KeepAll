#!/usr/bin/env python3
"""Makes every app icon from the one master picture.

Run from the project folder after replacing the master icon:

    python3 tool/generate_icons.py

Needs Pillow (`pip install pillow`). The master is a square PNG with its own
solid background; a 1024x1024 master gives the sharpest iOS/macOS icons.
"""
import json
import os

from PIL import Image, ImageDraw

MASTER = 'assets/Icon/lifekeeper_app_icon_512x512_original_background.png'
# In-app logo (onboarding, About): rounded corners, transparent outside.
IN_APP = 'assets/Icon/app_logo.png'

src = Image.open(MASTER).convert('RGBA')
bg = src.getpixel((0, 0))[:3]  # the master's own cream background
BG_HEX = '#%02X%02X%02X' % bg


def resized(size):
    return src.resize((size, size), Image.LANCZOS)


def on_canvas(size, scale, transparent=False):
    """Master scaled to [scale] of a [size] square, centred."""
    canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0) if transparent else bg + (255,))
    inner = round(size * scale)
    off = (size - inner) // 2
    canvas.paste(resized(inner), (off, off))
    return canvas


def rounded(size, radius_ratio=0.225):
    img = resized(size)
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, size - 1, size - 1), round(size * radius_ratio), fill=255)
    out = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    out.paste(img, (0, 0), mask)
    return out


def save(img, path, rgb=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    (img.convert('RGB') if rgb else img).save(path, optimize=True)
    print('  ', path, img.size)


# ---------------------------------------------------------------- Android
res = 'android/app/src/main/res'
densities = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
for name, d in densities.items():
    # Legacy icon (Android 7 and older): the full square picture.
    save(resized(round(48 * d)), f'{res}/mipmap-{name}/ic_launcher.png')
    # Adaptive icon foreground (Android 8+): 108dp layer of which launchers
    # show a circle/squircle of ~72dp. The drawing's furthest point is ~79%
    # of the half-width out, so the picture is drawn 74dp wide: the whole
    # house stays inside a round mask with a small margin.
    save(on_canvas(round(108 * d), 74 / 108), f'{res}/mipmap-{name}/ic_launcher_foreground.png')
os.makedirs(f'{res}/mipmap-anydpi-v26', exist_ok=True)
with open(f'{res}/mipmap-anydpi-v26/ic_launcher.xml', 'w') as f:
    f.write('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
''')
with open(f'{res}/values/ic_launcher_background.xml', 'w') as f:
    f.write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py: the app icon's own background. -->
<resources>
    <color name="ic_launcher_background">{BG_HEX}</color>
</resources>
''')
# Splash logo for Android 11 and older (12+ shows the launcher icon itself).
for name, d in densities.items():
    save(rounded(round(120 * d)), f'{res}/drawable-{name}/launch_logo.png')


def notification_icon(size):
    """Status-bar icon: Android draws only the alpha channel, so a coloured
    picture turns into a grey square. A white house with a tick cut out,
    drawn on a 24dp grid (the size Android uses), supersampled for smooth
    edges."""
    ss = 8
    k = size * ss / 24
    img = Image.new('RGBA', (size * ss, size * ss), (255, 255, 255, 0))
    draw = ImageDraw.Draw(img)
    pt = lambda x, y: (x * k, y * k)
    house = [(12, 2.5), (22, 11), (19, 11), (19, 21.5), (5, 21.5), (5, 11), (2, 11)]
    draw.polygon([pt(*p) for p in house], fill=(255, 255, 255, 255))
    draw.line([pt(8.3, 15.4), pt(11, 18), pt(15.9, 13)], fill=(255, 255, 255, 0), width=round(2.2 * k), joint='curve')
    for x, y in [(8.3, 15.4), (15.9, 13)]:  # round line ends
        r = 1.1 * k
        draw.ellipse((x * k - r, y * k - r, x * k + r, y * k + r), fill=(255, 255, 255, 0))
    return img.resize((size, size), Image.LANCZOS)


for name, d in densities.items():
    save(notification_icon(round(24 * d)), f'{res}/drawable-{name}/ic_notification.png')
# Release builds strip resources that no Android code references. The
# notification icon is only named from Dart, so it must be kept explicitly,
# or reminders fail silently in the Play Store version.
os.makedirs(f'{res}/raw', exist_ok=True)
with open(f'{res}/raw/keep.xml', 'w') as f:
    f.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. Keeps resources only referenced
     from Dart (notification icon) out of release resource shrinking. -->
<resources xmlns:tools="http://schemas.android.com/tools"
    tools:keep="@drawable/ic_notification,@mipmap/ic_launcher" />
''')

# ---------------------------------------------------------------- iOS
# App Store icons must be square with no transparency; iOS rounds them.
ios = 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
for entry in json.load(open(f'{ios}/Contents.json'))['images']:
    pt = float(entry['size'].split('x')[0])
    px = round(pt * int(entry['scale'][0]))
    save(resized(px), f"{ios}/{entry['filename']}", rgb=True)
launch = 'ios/Runner/Assets.xcassets/LaunchImage.imageset'
for scale, suffix in [(1, ''), (2, '@2x'), (3, '@3x')]:
    save(rounded(120 * scale), f'{launch}/LaunchImage{suffix}.png')

# ---------------------------------------------------------------- macOS
# macOS icons are a rounded square with a margin (824 of 1024).
mac = 'macos/Runner/Assets.xcassets/AppIcon.appiconset'
mac_master = Image.new('RGBA', (1024, 1024), (0, 0, 0, 0))
mac_master.paste(rounded(824, 0.225), (100, 100))
for s in [16, 32, 64, 128, 256, 512, 1024]:
    save(mac_master.resize((s, s), Image.LANCZOS), f'{mac}/app_icon_{s}.png')

# ---------------------------------------------------------------- Web
save(resized(32), 'web/favicon.png')
save(resized(192), 'web/icons/Icon-192.png')
save(resized(512), 'web/icons/Icon-512.png')
# Maskable: the browser may cut to a circle of 80% width; keep a margin.
save(on_canvas(192, 0.9), 'web/icons/Icon-maskable-192.png')
save(on_canvas(512, 0.9), 'web/icons/Icon-maskable-512.png')

# ---------------------------------------------------------------- Windows
ico = rounded(256)
ico.save('windows/runner/resources/app_icon.ico', sizes=[(s, s) for s in [16, 24, 32, 48, 64, 128, 256]])
print('   windows/runner/resources/app_icon.ico')

# ---------------------------------------------------------------- In-app / Linux
save(rounded(512), IN_APP)
print('Done. Icon background colour:', BG_HEX)
