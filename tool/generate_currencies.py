"""Generates lib/core/currency_data.g.dart from Unicode CLDR (via Babel).

    pip install babel
    python3 tool/generate_currencies.py

Includes every currency that is legal tender somewhere today, with its
English symbol, number of decimals, the countries that use it, and names of
currencies and countries in every app language (for display and search).

Each currency also gets a realistic example amount for input hints: roughly
what a small purchase (about EUR 12.50) costs in it, rounded to a friendly
number. Exchange rates are fetched once at generation time; they only need
to be the right order of magnitude.
"""
import datetime
import json
import math
import pathlib
import urllib.request

from babel import Locale
from babel.numbers import (get_currency_name, get_currency_precision,
                           get_currency_symbol, get_territory_currencies)

LANGS = ['en', 'de', 'fr', 'es', 'it', 'nl', 'pl']
OUT = pathlib.Path(__file__).resolve().parent.parent / 'lib/core/currency_data.g.dart'


def dart(s: str) -> str:
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def cap(s: str) -> str:
    return s[:1].upper() + s[1:]


EXAMPLE_EUR = 12.5


def fetch_rates() -> dict[str, float]:
    try:
        with urllib.request.urlopen('https://open.er-api.com/v6/latest/EUR', timeout=20) as r:
            return json.load(r)['rates']
    except Exception as e:  # offline: examples fall back to 12.50-style
        print('warning: no exchange rates:', e)
        return {}


def example_minor(code: str, decimals: int, rates: dict[str, float]) -> int:
    """A friendly example price in minor units, e.g. 1250 (EUR 12.50),
    3900 00 (PKR 3900), 2200 (JPY 2200)."""
    rate = rates.get(code)
    value = EXAMPLE_EUR * rate if rate else EXAMPLE_EUR
    if value < 100:
        step = 0.5 if decimals > 0 else 1
        value = max(step, round(value / step) * step)
    else:
        magnitude = 10 ** (math.floor(math.log10(value)) - 1)  # keep 2 significant digits
        value = round(value / magnitude) * magnitude
    return int(round(value * 10 ** decimals))


en = Locale('en')
today = datetime.date.today()
territories: dict[str, set[str]] = {}
for t in en.territories:
    if len(t) != 2 or not t.isalpha():
        continue
    try:
        found = get_territory_currencies(t, today, tender=True, non_tender=False)
    except Exception:
        continue
    for c in found:
        territories.setdefault(c, set()).add(t)

codes = sorted(territories)
rates = fetch_rates()
used_countries = sorted({t for ts in territories.values() for t in ts})

lines = [
    '// GENERATED by tool/generate_currencies.py from Unicode CLDR. Do not edit.',
    '// ignore_for_file: lines_longer_than_80_chars',
    '',
    '/// (code, symbol, decimals, ISO country codes using it, example price in minor units)',
    'const currencyTable = <(String, String, int, List<String>, int)>[',
]
for c in codes:
    countries = ', '.join(dart(t) for t in sorted(territories[c]))
    digits = get_currency_precision(c)
    lines.append(f'  ({dart(c)}, {dart(get_currency_symbol(c, "en"))}, {digits}, [{countries}], {example_minor(c, digits, rates)}),')
lines += ['];', '', '/// Currency names per language.', 'const currencyNames = <String, Map<String, String>>{']
for lang in LANGS:
    lines.append(f"  '{lang}': {{")
    for c in codes:
        lines.append(f'    {dart(c)}: {dart(cap(get_currency_name(c, locale=lang)))},')
    lines.append('  },')
lines += ['};', '', '/// Country names per language (only countries that appear above).', 'const countryNames = <String, Map<String, String>>{']
for lang in LANGS:
    names = Locale(lang).territories
    lines.append(f"  '{lang}': {{")
    for t in used_countries:
        lines.append(f'    {dart(t)}: {dart(names.get(t, t))},')
    lines.append('  },')
lines += ['};', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(codes)} currencies, {len(used_countries)} countries -> {OUT}')
